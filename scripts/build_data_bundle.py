"""Build an offline browser bootstrap from the validated JSON source files."""
import json
from pathlib import Path
from classify_notes import load_dataset, dataset_hash, validate_envelope, read_json

root = Path(__file__).resolve().parents[1]


def build():
    notes, groups = load_dataset(root / 'data/notes.json', root / 'data/groups.json')
    offline = read_json(root / 'data/classifications.offline.json')
    # The fixture is validated by the same validator used for real model outputs.
    validate_envelope(offline, notes, groups, expected_mode='offline')
    bundle = {'notes': notes, 'groups': groups, 'offline': offline}
    payload = json.dumps(bundle, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    (root / 'data/offline-bundle.js').write_text(
        '// Generated by scripts/build_data_bundle.py. Offline fixtures, not model output.\n'
        'globalThis.RE_BOOTSTRAP=' + payload + ';\n', encoding='utf-8')
    print('Offline bootstrap built for dataset ' + dataset_hash(notes, groups))


if __name__ == '__main__':
    build()
